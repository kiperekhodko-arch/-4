bool valid(int x);          // Функція перевірки належності числа до діапазону [-100, 100]
void showMenu();            // Функція організації меню користувача (Завдання 3)
void task_1();              // Функція виконання завдання 1
void task_2();              // Функція виконання завдання 2
long power_3(int n);        // Функція піднесення у 3-й ступінь (Приклад з методички)

// ---------------------------------------------------
// ГОЛОВНА ФУНКЦІЯ ПРОГРАМИ
// ---------------------------------------------------

int main() {
    setlocale(LC_ALL, "Ukrainian");
    
    // Запуск головного меню управління програмою
    showMenu();

    return 0;
}

// ---------------------------------------------------
// ВИЗНАЧЕННЯ ФУНКЦІЙ (Реалізація логіки)
// ---------------------------------------------------

/**
 * Перевіряє, чи входять вхідні дані в обов'язковий діапазон [-100, 100].
 * Повертає true, якщо число коректне, і false у протилежному випадку.
 */
bool valid(int x) {
    return (x >= -100 && x <= 100);
}

/**
 * Завдання 3: Меню користувача.
 * Реалізовано у вигляді окремої процедури без параметрів.
 */
void showMenu() {
    int choice;
    do {
        cout << "\n=========================================" << endl;
        cout << "              ГОЛОВНЕ МЕНЮ" << endl;
        cout << "=========================================" << endl;
        cout << "1. Виконати Завдання 1" << endl;
        cout << "2. Виконати Завдання 2" << endl;
        cout << "3. Вийти з програми" << endl;
        cout << "=========================================" << endl;
        cout << "Оберіть пункт меню: ";
        cin >> choice;

        // Захист на випадок, якщо користувач введе літеру замість цифри
        if (cin.fail()) {
            cin.clear();
            cin.ignore(10000, '\n');
            choice = 0;
        }

        switch (choice) {
            case 1:
                task_1();
                break;
            case 2:
                task_2();
                break;
            case 3:
                cout << "\nВихід з програми. До побачення!" << endl;
                break;
            default:
                cout << "\nПомилка: Некоректний вибір! Спробуйте ще раз." << endl;
        }
    } while (choice != 3); // Цикл повторюється, поки користувач не вибере вихід
}

/**
 * Завдання 1: Демонстраційна функція першого завдання
 */
void task_1() {
    int A;
    cout << "\n--- [Завдання 1] ---" << endl;
    cout << "Введіть ціле число A: ";
    cin >> A;

    // Перевірка коректності вхідних даних за правилами діапазону [-100, 100]
    if (!valid(A)) {
        cout << "Помилка: введені дані некоректні! Число виходить за межі діапазону [-100, 100]." << endl;
        cout << "Розрахунки не виконуються." << endl;
        return; // Миттєвий вихід із функції виконання без розрахунків
    }

    // Приклад розрахунку для завдання 1
    int result = A * A;
    cout << "Результат обчислення (квадрат числа): " << result << endl;
}

/**
 * Завдання 2: Виправлена функція піднесення до 3-го ступеня
 */
void task_2() {
    int A;
    cout << "\n--- [Завдання 2] ---" << endl;
    cout << "Введіть ціле число A: ";
    cin >> A;

    // Перевірка діапазону за допомогою створеної функції valid()
    if (valid(A)) {
        long result = power_3(A);
        cout << "Дані коректні. Результат піднесення до 3-го ступеня: " << result << endl;
    } else {
        cout << "Помилка: введені дані некоректні (поза діапазоном [-100, 100])!" << endl;
        cout << "Розрахунок скасовано." << endl;
    }
}

/**
 * Функція з прикладу в методичці: Піднесення числа до третього ступеня.
 */
long power_3(int n) {
    return (long)n * n * n; // Повертає куб числа
}