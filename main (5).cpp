bool isValid(int x);          // Функция проверки принадлежности к диапазону [-100, 100]
void showMenu();             // Функция организации меню пользователя (Задание 3)
void task_1();               // Функция выполнения Задания 1
void task_2();               // Функция выполнения Задания 2
long power_3(int pA);        // Функция возведения в 3-ю степень (Пример из методички)


// ============================================================================
// ГЛАВНАЯ ФУНКЦИЯ ПРОГРАММЫ
