/**
 * Проверяет, входят ли входные данные в обязательный диапазон [-100, 100].
 * Возвращает true, если число корректно, и false в противном случае.
 */
bool isValid(int x) {
    return (x >= -100 && x <= 100);
}

/**
 * Задание 3: Меню пользователя.
 * Реализовано в виде отдельной процедуры без параметров.
 */
void showMenu() {
    int choice;
    do {
        cout << "\n=========================================" << endl;
        cout << "             ГОЛОВНЕ МЕНЮ" << endl;
        cout << "=========================================" << endl;
        cout << "1. Виконати Завдання 1" << endl;
        cout << "2. Виконати Завдання 2" << endl;
        cout << "3. Вийти з програми" << endl;
        cout << "-----------------------------------------" << endl;
        cout << "Оберіть пункт меню: ";
        cin >> choice;

        switch (choice) {
            case 1:
                task_1();
                break;
            case 2:
                task_2();
                break;
            case 3:
                cout << "\nВихід з програми. До побачення!" << endl;
                break;
            default:
                cout << "\nПомилка: Некоректний вибір! Спробуйте ще раз." << endl;
        }
    } while (choice != 3); // Цикл повторяется, пока пользователь не выберет выход
}

/**
 * Завдання 1: Демонстрационная функция первого задания
 */
void task_1() {
    int A;
    cout << "\n--- [Завдання 1] ---" << endl;
    cout << "Введіть ціле число A: ";
    cin >> A;

    // Проверка корректности входных данных по правилу диапазона [-100, 100]
    if (!isValid(A)) {
        cout << "Помилка: введені дані некоректні! Число виходить за межі діапазону [-100, 100]." << endl;
        cout << "Розрахунки не виконуються." << endl;
        return; // Мгновенный выход из функции без выполнения расчетов
    }

    // Пример расчета для Задания 1
    int result = A * A;
    cout << "Результат обчислення (квадрат числа): " << result << endl;
}

/**
 * Завдання 2: Исправленная функция, в которой возникала ошибка компиляции
 */
void task_2() {
    int A;
    cout << "\n--- [Завдання 2] ---" << endl;
    cout << "Введіть ціле число A: ";
    cin >> A;

    // ИСПРАВЛЕНО: Проверка диапазона выполняется БЕЗ повторного указания типов данных "int"
    if (A >= -100 && A <= 100) {
        // Если условие истинно, выполняем расчеты
        long result = power_3(A);
        cout << "Дані коректні. Результат піднесення до 3-го ступеня: " << result << endl;
    } 
    else {
        // Если данные некорректны — выводим сообщение об ошибке (требование методички)
        cout << "Помилка: введені дані некоректні (поза діапазоном [-100, 100])!" << endl;
        cout << "Розрахунки скасовано." << endl;
    }
}

/**
 * Функция из примера в методичке: Возведение числа в третью степень.
 * Оптимизирована (убрана избыточная проверка на ноль).
 */
long power_3(int pA) {
    return (pA * pA * pA); // Возвращает куб числа
}
